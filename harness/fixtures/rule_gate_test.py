class Frontmatter(unittest.TestCase):
    def parse(self, fm: str):
        return gate.parse_paths_frontmatter(f"---\n{fm}\n---\nbody\n")

    def test_block_list_quoted_and_unquoted(self):
        self.assertEqual(self.parse('paths:\n  - "src/**/*.py"\n  - tests/*.py\n  - \'a.md\''),
                         ["src/**/*.py", "tests/*.py", "a.md"])

    def test_block_list_at_column_zero_with_comments(self):
        fm = "paths:\n- src/*.py  # the sources\n# a note\n- b.md\nother: 1"
        self.assertEqual(self.parse(fm), ["src/*.py", "b.md"])

    def test_flow_list(self):
        self.assertEqual(self.parse('paths: ["**/*.ts", \'**/*.tsx\', docs/*.md]'),
                         ["**/*.ts", "**/*.tsx", "docs/*.md"])

    def test_comma_string_plain_and_quoted(self):
        self.assertEqual(self.parse("paths: src/*.py, tests/*.py"), ["src/*.py", "tests/*.py"])
        self.assertEqual(self.parse('paths: "src/*.py, docs/**"'), ["src/*.py", "docs"])

    def test_braces_expand_and_commas_inside_braces_do_not_split(self):
        self.assertEqual(sorted(self.parse('paths: "src/**/*.{ts,tsx}, lib/*.js"')),
                         ["lib/*.js", "src/**/*.ts", "src/**/*.tsx"])
        self.assertEqual(sorted(self.parse('paths:\n  - "{a,b}/{c,d}.py"')),
                         ["a/c.py", "a/d.py", "b/c.py", "b/d.py"])

    def test_one_trailing_double_star_is_stripped(self):
        self.assertEqual(self.parse('paths:\n  - "docs/**"\n  - "x/**/**"'), ["docs", "x/**"])

    def test_a_scalar_on_the_lines_after_the_key(self):
        self.assertEqual(self.parse('paths:\n  "**/*.py"'), ["**/*.py"])
        self.assertEqual(self.parse("paths:\n  src/*.py,\n  docs/**\nother: 1"), ["src/*.py", "docs"])

    def test_block_scalars_folded_and_literal(self):
        self.assertEqual(self.parse("paths: >-\n  **/*.py,\n  **/*.go"), ["**/*.py", "**/*.go"],
                         "the old parser read the indicator >- as the glob")
        self.assertEqual(self.parse("paths: |\n  **/*.py, **/*.go\n"), ["**/*.py", "**/*.go"])
        self.assertIsNone(self.parse("paths: >\n"), "an empty block scalar is no paths at all")

    def test_a_quoted_key(self):
        self.assertEqual(self.parse('"paths":\n  - "**/*.py"'), ["**/*.py"])
        self.assertEqual(self.parse("'paths': src/*.py"), ["src/*.py"])

    def test_crlf_frontmatter(self):
        text = '---\r\npaths:\r\n  - "src/*.py"\r\n---\r\nbody\r\n'
        self.assertEqual(gate.parse_paths_frontmatter(text), ["src/*.py"])

    def test_unconditional_shapes_are_none(self):
        self.assertIsNone(gate.parse_paths_frontmatter("# no frontmatter at all\n"))
        self.assertIsNone(self.parse("description: no paths key"))
        self.assertIsNone(self.parse("paths:"))
        self.assertIsNone(self.parse("paths: []"))
        self.assertIsNone(self.parse('paths:\n  - "**"\n  - "**/**"'))
        self.assertEqual(gate.raw_paths("---\npaths:\n---\n"), [],
                         "an empty value is a declared key, which the coverage check reports")


