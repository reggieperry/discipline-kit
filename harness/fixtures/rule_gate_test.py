#!/usr/bin/env python3
"""Tests for reference/rule_gate.py, the PreToolUse gate that refuses a write whose path-scoped
rules are not in the calling agent's context. Stdlib unittest; run: python3 <this file>.

Hermetic: every case builds its own project, home directory, state directory, log and
transcripts under a temporary directory, and passes the environment to the gate explicitly, so
nothing reads or writes the operator's ~/.claude. The transcripts are synthetic but every entry
copies the shape Claude Code 2.1.286 wrote in the probe sessions (attachment entries, assistant
tool_use entries with `wireToolInputs`, user tool_result entries with and without
`toolUseResult`, the compact_boundary system entry and the compaction summary), with placeholder
paths.

  MATCHER      every glob x path pair in rule_gate_vectors.json, generated by the node-ignore
               bundled in Claude Code, replayed against the Python port; the vector file must
               cover every glob the kit ships, so a glob edit without a regeneration fails here;
               the places JavaScript's regex dialect differs from Python's
  FRONTMATTER  block lists quoted and not, a flow list, a comma string, braces, a trailing
               `/**`, a scalar on the next line, block scalars, a quoted key, and the shapes
               that make a rule unconditional (and so skipped)
  RULES        nested `.claude` directories, the user-scope exclusion, the project boundary,
               symlinked rule directories, a worktree nested in its repo, content dedupe
  COUNTING     each way a rule counts as loaded, each near miss that must not count, and a
               transcript line many read chunks long
  DECISION     the refusal and its inlined text, the size cap, the sibling window, the BLIND
               breaker, a stale pending entry after compaction, the kill switch, fail-open
  SAME RESPONSE  a result answering another call of the checked call's own response does not
               count, and a later call of that response is a sibling however long it waited
  ANOTHER HOOK  a refusal whose text another hook's refusal replaced is given again, never
               called a sibling or blind, until the breaker's limit
  DEFERRAL     a copy outside the project steps aside for the project's own wired copy, through
               settings.json or settings.local.json; it does not when that file is missing, the
               matcher leaves out the tool, the settings do not parse, or $CLAUDE_PROJECT_DIR is
               unset; the project's copy never steps aside
  END TO END   the hook as a subprocess: a refusal, then the same write allowed once the
               refusal's own text is in the transcript, and garbage on stdin still exiting 0

Every refusal has a negative control beside it: a gate only ever observed refusing is as unknown
as one only ever observed allowing.
"""
