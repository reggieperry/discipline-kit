class GoldenVectors(unittest.TestCase):
    """The Python port against the node-ignore that Claude Code bundles."""

    @classmethod
    def setUpClass(cls):
        cls.v = json.loads(VECTORS.read_text())

    def test_every_single_glob_vector(self):
        bad, n = [], 0
        for g in self.v["globs"]:
            want = set(self.v["matches"][g])
            norm = gate.normalize_globs([g])
            self.assertIsNotNone(norm, f"vector glob {g!r} normalizes to unconditional")
            for i, p in enumerate(self.v["paths"]):
                n += 1
                if gate.match(norm, p) != (i in want):
                    bad.append((g, p, i in want))
        self.assertGreater(n, 9000, "the vector file shrank; regenerate it rather than trim it")
        self.assertEqual(bad, [], f"{len(bad)} of {n} pairs disagree with node-ignore")

    def test_every_multi_glob_set(self):
        for s in self.v["sets"]:
            with self.subTest(s=s):
                self.assertEqual(gate.match(gate.normalize_globs(s["globs"]), s["path"]),
                                 s["match"])

    def test_vectors_cover_every_shipped_glob(self):
        """A glob edited in a rule without regenerating the vectors is unpinned. Fail instead."""
        shipped = set()
        for f in sorted((REPO / "claude-project" / "rules").glob("*.md")):
            shipped.update(gate.split_paths_value(gate.raw_paths(f.read_text()) or []))
        self.assertTrue(shipped, "no shipped globs read; the check would pass having read nothing")
        missing = sorted(shipped - set(self.v["globs"]))
        self.assertEqual(missing, [], "regenerate rule_gate_vectors.json for these globs")

    def test_provenance_names_the_source_and_the_generator(self):
        """Private paths in the file are the scrub gate's to catch; it scans every file."""
        self.assertIn("node-ignore bundled in Claude Code 2.1.286", self.v["provenance"])
        self.assertTrue(self.v["generator"] and self.v["command"])
        self.assertIn("ignore_bundled.cjs", "\n".join(self.v["generator"]))

    def test_provenance_says_how_to_recreate_the_matcher_the_generator_needs(self):
        """A generator that needs a file nobody can make is not a regeneration step."""
        for how in ("npm pack ignore@7.0.5", 'Symbol.for("setupWindows")'):
            self.assertIn(how, self.v["provenance"])

    def test_vectors_include_the_named_paths(self):
        for p in ("docs/adrs/ADR-0001-x.md", "stories/STORY-0001-x.md", "x/tests/a.py",
                  "packs/x/scripts/a.sh", "project/plugins.sbt", "../out.py", "latest.md"):
            self.assertIn(p, self.v["paths"])


class Matcher(unittest.TestCase):
    def test_case_insensitive(self):
        self.assertTrue(gate.match(["**/*.py"], "SRC/A.PY"))

    def test_star_does_not_cross_slash_and_double_star_does(self):
        self.assertFalse(gate.match(["src/*.py"], "src/sub/a.py"))
        self.assertTrue(gate.match(["src/**/*.py"], "src/sub/deep/a.py"))

    def test_a_pattern_with_a_slash_is_anchored_and_one_without_is_not(self):
        self.assertFalse(gate.match(["scripts/*.py"], "x/scripts/a.py"))
        self.assertTrue(gate.match(["README.md"], "sub/README.md"))

    def test_a_directory_pattern_matches_every_file_under_it(self):
        self.assertTrue(gate.match(["tests"], "pkg/tests/sub/a.py"))

    def test_parent_relative_and_absolute_paths_never_match(self):
        for p in ("../out.py", "..x/a.py", "/abs/a.py", "./a.py", ""):
            self.assertFalse(gate.match(["**/*.py", "**"], p), p)

    def test_javascript_regex_dialect_where_python_reads_it_differently(self):
        """node-ignore builds JavaScript regex source. Each expectation is node-ignore's answer,
        and the golden vectors pin the same globs."""
        self.assertTrue(gate.match(["\\a*"], "a"), "JavaScript reads \\a as the letter a; "
                        "Python reads it as BEL")
        self.assertTrue(gate.match(["\\p*"], "p"), "Python refuses \\p and the glob was dropped")
        self.assertTrue(gate.match(["\\e"], "e"))
        self.assertFalse(gate.match(["([] -[a-c]"], "+/(B"), "[] is an empty class in JavaScript")
        self.assertTrue(gate.match(["**/[/b["], "B"), "a [ inside a class is a plain character")


