DENY_PREFIX = "PreToolUse:Write hook error: "


class Transcript:
    """Appends entries in the shapes Claude Code writes, with placeholder ids and paths."""

    def __init__(self, path: Path, cwd: str, session: str, agent: str | None = None):
        self.path, self.cwd, self.session, self.agent = path, cwd, session, agent
        path.parent.mkdir(parents=True, exist_ok=True)
        path.touch()
        self.parent: str | None = None

    def _base(self, **fields) -> dict:
        e = {"parentUuid": self.parent, "isSidechain": self.agent is not None}
        if self.agent:
            e["agentId"] = self.agent
        e.update(fields)
        e.update({"uuid": str(uuid.uuid4()), "timestamp": "2026-10-01T03:10:24.369Z",
                  "userType": "external", "entrypoint": "sdk-cli", "cwd": self.cwd,
                  "sessionId": self.session, "version": "2.1.286", "gitBranch": "main"})
        self.parent = e["uuid"]
        return e

    def write(self, entry: dict) -> dict:
        with self.path.open("a", encoding="utf-8") as f:
            f.write(json.dumps(entry) + "\n")
        return entry

    def raw(self, text: str) -> None:
        with self.path.open("a", encoding="utf-8") as f:
            f.write(text)

    def user_prompt(self, text: str) -> dict:
        return self.write(self._base(type="user", message={"role": "user", "content": text}))

    def instructions(self, *paths: str) -> dict:
        files = [{"path": p, "type": "Project", "content": "..."} for p in paths]
        return self.write(self._base(type="attachment",
                                     attachment={"type": "instructions", "files": files},
                                     renderedRole="user"))

    def nested_memory(self, path: str) -> dict:
        content = {"path": path, "type": "Project", "content": "...", "globs": ["src/**/*.py"],
                   "contentDiffersFromDisk": True, "rawContent": "..."}
        return self.write(self._base(type="attachment", renderedRole="system", attachment={
            "type": "nested_memory", "path": path, "content": content,
            "displayPath": ".claude/rules/" + os.path.basename(path)}))

    def file_attachment(self, path: str, text: str) -> dict:
        n = text.count("\n") + 1
        return self.write(self._base(type="attachment", renderedRole="system", attachment={
            "type": "file", "filename": path,
            "content": {"type": "text", "file": {"filePath": path, "content": text,
                                                 "numLines": n, "startLine": 1, "totalLines": n}},
            "displayPath": os.path.basename(path)}))

    def tool_use(self, name: str, tool_input: dict, msg_id: str | None = None,
                 tid: str | None = None) -> str:
        """One tool call. Claude Code writes each call of a response as its own entry, all with
        the response's message.id, so calls of one response pass the same `msg_id`."""
        tid = tid or "toolu_" + uuid.uuid4().hex[:24]
        block = {"type": "tool_use", "id": tid, "name": name, "input": tool_input,
                 "caller": {"type": "direct"}}
        message = {"model": "claude-haiku-4-5-20251001",
                   "id": msg_id or "msg_" + uuid.uuid4().hex[:24],
                   "type": "message", "role": "assistant", "content": [block],
                   "stop_reason": "tool_use"}
        self.write(self._base(type="assistant", message=message, wireToolInputs={tid: tool_input},
                              requestId="req_" + uuid.uuid4().hex[:24]))
        return tid

    def tool_result(self, tid: str, content, tur=None, is_error: bool = False) -> dict:
        block = {"tool_use_id": tid, "type": "tool_result", "content": content}
        if is_error:
            block["is_error"] = True
        fields = {"type": "user", "message": {"role": "user", "content": [block]},
                  "promptId": str(uuid.uuid4())}
        if tur is not None:
            fields["toolUseResult"] = tur
        return self.write(self._base(**fields))

    def read(self, path: str, text: str, *, with_tur: bool = True, **extra) -> str:
        """A Read and its result. `extra` (offset, limit) makes it partial, as the tool would."""
        tid = self.tool_use("Read", {"file_path": path, **extra})
        lines = text.split("\n")
        start = int(extra.get("offset", 1))
        shown = lines[start - 1:start - 1 + int(extra.get("limit", len(lines)))]
        numbered = "\n".join(f"{start + i}\t{ln}" for i, ln in enumerate(shown))
        tur = {"type": "text", "file": {"filePath": path, "content": "\n".join(shown),
                                        "numLines": len(shown), "startLine": start,
                                        "totalLines": len(lines)}}
        self.tool_result(tid, numbered, tur if with_tur else None)
        return tid

    def read_unchanged(self, path: str, *, with_tur: bool = True) -> str:
        tid = self.tool_use("Read", {"file_path": path})
        tur = {"type": "file_unchanged", "file": {"filePath": path}}
        self.tool_result(tid, "Wasted call — file unchanged since your last Read. Refer to "
                         "that earlier tool_result instead.", tur if with_tur else None)
        return tid

    def boundary(self) -> dict:
        e = self._base(type="system", subtype="compact_boundary", content="Conversation compacted",
                       isMeta=False, level="info",
                       compactMetadata={"trigger": "manual", "preTokens": 25741,
                                        "postTokens": 3001})
        e["parentUuid"] = None
        return self.write(e)

    def summary(self, text: str) -> dict:
        return self.write(self._base(
            type="user", isVisibleInTranscriptOnly=True, isCompactSummary=True,
            message={"role": "user", "content": "This session is being continued from a "
                     "previous conversation that ran out of context.\n\nSummary:\n" + text}))

    def denied(self, tid: str, reason: str) -> dict:
        """A refused tool call's result, in the measured shape."""
        return self.tool_result(tid, DENY_PREFIX + reason, "Error: " + DENY_PREFIX + reason,
                                is_error=True)


class GateCase(unittest.TestCase):
    """A project with one path rule and one unconditional rule, a home, and a transcript."""

    def setUp(self):
        self._td = tempfile.TemporaryDirectory()
        self.root = Path(self._td.name).resolve()
        self.home = self.root / "home"
        self.proj = self.root / "proj"
        self.rules = self.proj / ".claude" / "rules"
        self.rules.mkdir(parents=True)
        (self.proj / "src").mkdir()
        self.py_rule = self.rules / "py.md"
        self.py_rule.write_text(PY_RULE)
        (self.rules / "always.md").write_text(ALWAYS_RULE)
        (self.proj / "src" / "a.py").write_text("def add(x, y):\n    return x + y\n")
        self.session = str(uuid.uuid4())
        self.tpath = (self.home / ".claude" / "projects" / "-placeholder-proj"
                      / (self.session + ".jsonl"))
        self.t = Transcript(self.tpath, str(self.proj), self.session)
        self.t.instructions(str(self.home / ".claude" / "CLAUDE.md"), str(self.rules / "always.md"))
        self.t.user_prompt("create src/b.py")
        self.log = self.root / "rule-gate.log"
        self.state = self.root / "state"
        self.env = {"HOME": str(self.home), "CLAUDE_PROJECT_DIR": str(self.proj),
                    "DISCIPLINE_RULE_GATE_LOG": str(self.log),
                    "DISCIPLINE_RULE_GATE_STATE": str(self.state)}
        self.now = 1_800_000_000.0

    def tearDown(self):
        self._td.cleanup()

    def hook_input(self, target=None, tool="Write", agent=None, tid=None, **tool_input) -> dict:
        target = str(self.proj / "src" / "b.py") if target is None else target
        key = "notebook_path" if tool == "NotebookEdit" else "file_path"
        d = {"session_id": self.session, "transcript_path": str(self.tpath), "cwd": str(self.proj),
             "prompt_id": str(uuid.uuid4()), "permission_mode": "bypassPermissions",
             "hook_event_name": "PreToolUse", "tool_name": tool,
             "tool_input": {key: target, "content": "def mul(x, y):\n    return x * y\n",
                            **tool_input},
             "tool_use_id": tid or "toolu_" + uuid.uuid4().hex[:24]}
        if agent:
            d.update({"agent_id": agent, "agent_type": "general-purpose"})
        return d

    def decide(self, hook_input=None, now=None, **env):
        return gate.decide(hook_input or self.hook_input(), {**self.env, **env},
                           self.now if now is None else now)

    def assertDenied(self, out) -> str:
        self.assertIsNotNone(out, "want a refusal, got a silent allow")
        hso = out["hookSpecificOutput"]
        self.assertEqual(hso.get("permissionDecision"), "deny", out)
        return hso["permissionDecisionReason"]

    def assertAllowedSilently(self, out):
        self.assertIsNone(out, f"want a silent allow, got {out}")

    def assertAllowedWithWarning(self, out) -> str:
        self.assertIsNotNone(out, "want an allow with a warning, got a silent allow")
        hso = out["hookSpecificOutput"]
        self.assertNotIn("permissionDecision", hso,
                         "an allow must leave the decision to the permission system")
        self.assertTrue(hso.get("additionalContext"), out)
        return hso["additionalContext"]

    def log_lines(self) -> list[str]:
        return self.log.read_text().splitlines() if self.log.exists() else []


