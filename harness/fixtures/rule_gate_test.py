class ApplicableRules(GateCase):
    def names(self, target, root=None, home=None):
        return [os.path.relpath(r.path, self.root) for r in gate.applicable_rules(
            str(target), str(root or self.proj), str(home or self.home))]

    def test_matching_rule_found_and_unconditional_skipped(self):
        self.assertEqual(self.names(self.proj / "src" / "b.py"), ["proj/.claude/rules/py.md"])
        self.assertEqual(self.names(self.proj / "README.md"), [])

    def test_a_nested_claude_dir_matches_relative_to_its_own_directory(self):
        sub = self.proj / "pkg"
        (sub / ".claude" / "rules").mkdir(parents=True)
        (sub / ".claude" / "rules" / "docs.md").write_text(DOC_RULE)
        self.assertEqual(self.names(sub / "docs" / "x.md"), ["proj/pkg/.claude/rules/docs.md"])
        self.assertEqual(self.names(self.proj / "docs" / "x.md"), [])
        self.assertEqual(self.names(sub / "src" / "a.py"), [],
                         "src/**/*.py is anchored at proj, so pkg/src/a.py does not match it")

    def test_rules_in_subdirectories_of_rules_are_found(self):
        (self.rules / "lang").mkdir()
        (self.rules / "lang" / "test.md").write_text(TEST_RULE)
        self.assertEqual(sorted(self.names(self.proj / "src" / "test_a.py")),
                         ["proj/.claude/rules/lang/test.md", "proj/.claude/rules/py.md"])

    def test_user_scope_rules_are_excluded(self):
        user = self.home / ".claude" / "rules"
        user.mkdir(parents=True)
        (user / "everything.md").write_text('---\npaths:\n  - "**/*.py"\n---\nUSER\n')
        inside = self.home / "work" / "a.py"
        self.assertEqual(self.names(inside, root=self.home), [])
        self.assertEqual(self.names(inside, root=self.home, home=self.root / "elsewhere"),
                         ["home/.claude/rules/everything.md"], "negative control")

    def test_a_target_outside_the_project_gets_no_rules(self):
        other = self.root / "other"
        (other / ".claude" / "rules").mkdir(parents=True)
        (other / ".claude" / "rules" / "py.md").write_text(PY_RULE)
        self.assertEqual(self.names(other / "src" / "b.py"), [])
        self.assertEqual(self.names(other / "src" / "b.py", root=other),
                         ["other/.claude/rules/py.md"], "negative control")

    def test_a_symlinked_rules_subdirectory_inside_the_project_is_followed(self):
        shared = self.proj / "tools" / "rules"
        shared.mkdir(parents=True)
        (shared / "test.md").write_text(TEST_RULE)
        (self.rules / "shared").symlink_to(Path("..", "..", "tools", "rules"))
        self.assertIn("proj/.claude/rules/shared/test.md",
                      self.names(self.proj / "src" / "test_a.py"))

    def test_a_symlink_that_leaves_the_project_is_skipped_and_a_cycle_ends(self):
        outside = self.root / "outside"
        outside.mkdir()
        (outside / "test.md").write_text(TEST_RULE)
        (self.rules / "ext").symlink_to(outside)
        (self.rules / "ext-file.md").symlink_to(outside / "test.md")
        (self.rules / "loop").symlink_to(self.rules)
        self.assertEqual(self.names(self.proj / "src" / "test_a.py"),
                         ["proj/.claude/rules/py.md"], "Claude Code skips a link out of the project")
        wider = self.names(self.proj / "src" / "test_a.py", root=self.root)
        self.assertEqual(len(wider), 2, "negative control: inside a wider project root the "
                         f"links are followed (two links to one file count once): {wider}")

    def nested_worktree(self) -> Path:
        """The layout `git worktree add .claude/worktrees/wt` leaves, without running git."""
        wt = self.proj / ".claude" / "worktrees" / "wt"
